export function authText(value,language='ru'){
 if(language==='ru')return value;
 const index=language==='uz'?1:0;
 if(copy[value])return copy[value][index];
 const code=value.match(/^Введите код из (\d+) цифр\.$/);if(code)return language==='uz'?`${code[1]} xonali kodni kiriting.`:`Enter the ${code[1]}-digit code.`;
 return value.replace('Код отправлен по SMS на',copy['Код отправлен по SMS на'][index]);
}
export function translateAuth(root,language='ru'){
 if(!root||language==='ru')return;
 const walker=document.createTreeWalker(root,4);let node;
 while((node=walker.nextNode())){if(node.parentElement.closest('[data-auth-user-value]'))continue;const text=node.textContent,trimmed=text.trim();node.textContent=text.replace(trimmed,authText(trimmed,language));}
}

